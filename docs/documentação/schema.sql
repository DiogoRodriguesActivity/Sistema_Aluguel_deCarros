CREATE TABLE usuario (
  id BIGSERIAL PRIMARY KEY,
  login VARCHAR(100) NOT NULL UNIQUE,
  senha VARCHAR(255) NOT NULL,
  papel VARCHAR(20) NOT NULL CHECK (papel IN ('CLIENTE','EMPRESA','BANCO'))
);

CREATE TABLE cliente (
  id BIGINT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE,
  rg VARCHAR(20) NOT NULL,
  cpf VARCHAR(14) NOT NULL UNIQUE,
  nome VARCHAR(150) NOT NULL,
  endereco VARCHAR(255) NOT NULL,
  profissao VARCHAR(100)
);

CREATE TABLE agente (
  id BIGINT PRIMARY KEY REFERENCES usuario(id) ON DELETE CASCADE,
  nome VARCHAR(150) NOT NULL
);

CREATE TABLE empresa (
  id BIGINT PRIMARY KEY REFERENCES agente(id) ON DELETE CASCADE,
  cnpj VARCHAR(18) NOT NULL UNIQUE
);

CREATE TABLE banco (
  id BIGINT PRIMARY KEY REFERENCES agente(id) ON DELETE CASCADE,
  cnpj VARCHAR(18) NOT NULL UNIQUE
);

CREATE TABLE rendimento (
  id BIGSERIAL PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE CASCADE,
  entidade_empregadora VARCHAR(150) NOT NULL,
  valor NUMERIC(12,2) NOT NULL CHECK (valor >= 0)
);

CREATE TABLE automovel (
  id BIGSERIAL PRIMARY KEY,
  matricula VARCHAR(30) NOT NULL UNIQUE,
  ano INT NOT NULL,
  marca VARCHAR(60) NOT NULL,
  modelo VARCHAR(60) NOT NULL,
  placa VARCHAR(10) NOT NULL UNIQUE,
  proprietario_id BIGINT REFERENCES usuario(id)
);

CREATE TABLE pedido (
  id BIGSERIAL PRIMARY KEY,
  data_criacao TIMESTAMP NOT NULL DEFAULT now(),
  status VARCHAR(20) NOT NULL DEFAULT 'CRIADO'
    CHECK (status IN ('CRIADO','EM_ANALISE','APROVADO','REPROVADO','CANCELADO')),
  cliente_id BIGINT NOT NULL REFERENCES cliente(id),
  automovel_id BIGINT NOT NULL REFERENCES automovel(id),
  agente_id BIGINT REFERENCES agente(id)
);

CREATE TABLE avaliacao_financeira (
  id BIGSERIAL PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedido(id) ON DELETE CASCADE,
  agente_id BIGINT NOT NULL REFERENCES agente(id),
  data TIMESTAMP NOT NULL DEFAULT now(),
  parecer VARCHAR(10) NOT NULL CHECK (parecer IN ('POSITIVO','NEGATIVO')),
  observacao TEXT
);

CREATE TABLE contrato_credito (
  id BIGSERIAL PRIMARY KEY,
  pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedido(id) ON DELETE CASCADE,
  banco_id BIGINT NOT NULL REFERENCES banco(id),
  valor NUMERIC(12,2) NOT NULL,
  taxa_juros NUMERIC(5,2) NOT NULL,
  parcelas INT NOT NULL,
  data DATE NOT NULL DEFAULT current_date
);

